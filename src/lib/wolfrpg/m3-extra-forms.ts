/**
 * The Arabic forms Mother 3's main font does not supply, drawn to match it.
 *
 * Twelve forms in Mother 3's table point at codes 0xA0 and above, and that
 * range of the font holds the game's own symbols — arrows, Greek letters, PK.
 * Taken at face value they render as a small circle or a diagonal line, which
 * is how صديقي lost its first letter on screen when this was first tried in
 * Pokémon. Seven more forms have no entry at all.
 *
 * Rather than invent a style, each is derived from a form that does exist in
 * that font, so the weight and the seat on the baseline match the rest:
 *
 *   ص  the isolated form exists; the final adds the joining pixel on the
 *      right, the initial drops the tail and runs the base to the left edge.
 *   ض  ص plus the dot.
 *   ط  the final ظ exists; ط is the same letter without its dot.
 *   ظ  the initial and medial come off that same final.
 *   ع  the initial and final exist; the medial adds a joining pixel.
 *   آ  the final exists; the isolated drops its joining pixel.
 *   ء  stands alone in every position, so one drawing serves all four.
 *
 * The pictures are 8 columns wide and seated the way Mother 3 seats its own
 * Arabic — the top row of the drawing is the top of the font's ink band, so
 * they line up with the shipped forms without any fitting.
 */

/** One drawn form: rows of `#` for ink, `.` for blank, 8 columns wide. */
export interface DrawnForm {
  rows: boolean[][];
  width: number;
}

