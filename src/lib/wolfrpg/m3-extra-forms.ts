const CELL_WIDTH = 8;
const CELL_HEIGHT = 16;

function parse(art: string): boolean[][] {
  const rows: boolean[][] = Array.from({ length: CELL_HEIGHT }, () =>
    new Array<boolean>(CELL_WIDTH).fill(false)
  );
  art.trim().split("\n").forEach((line, y) => {
    if (y >= CELL_HEIGHT) return;
    for (let x = 0; x < CELL_WIDTH && x < line.length; x++) rows[y][x] = line[x] === "#";
  });
  return rows;
}

/** ض is ص with the dot over the loop. */
function withDot(rows: boolean[][]): boolean[][] {
  const out = rows.map((r) => [...r]);
  out[2][6] = true;
  return out;
}

function form(rows: boolean[][]): DrawnForm {
  let width = 1;
  for (const row of rows) {
    for (let x = 0; x < row.length; x++) if (row[x]) width = Math.max(width, x + 1);
  }
  return { rows, width };
}

